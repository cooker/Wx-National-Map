// ---------- 1 月等温线（示意） ----------
// 规律：1 月北半球是冬季，同纬度陆地比海洋冷，所以等温线在大陆上向南（低纬）弯，在海洋上向北（高纬）弯；
// 北大西洋暖流经过的地方向北弯得最明显。南半球是夏季，海洋面积大，等温线比较平直，在大陆上略向南弯。
function bump(lng, center, half) {
  const d = Math.abs(lng - center)
  return d >= half ? 0 : Math.cos(d / half * Math.PI / 2)
}
function northLat(base, shift, lng) {
  const land = Math.max(bump(lng, 95, 75), bump(lng, -100, 40))            // 亚欧大陆、北美大陆
  const sea = Math.max(1.3 * bump(lng, -15, 35), 0.5 * bump(lng, -150, 30)) // 北大西洋、北太平洋
  return Math.min(80, base - shift * land + shift * sea)
}
function southLat(base, lng) {
  const land = Math.max(bump(lng, -62, 18), bump(lng, 25, 18), bump(lng, 135, 20))   // 南美、非洲、澳大利亚
  return base - 4 * land
}
