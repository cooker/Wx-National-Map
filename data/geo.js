const TYPE_LABEL = { continent: '大洲', ocean: '大洋', country: '国家', feature: '山河湖海', region: '区域', grid: '经纬线与五带', physical: '高中自然地理' }
const TYPE_COLOR = { continent: '#b84300', ocean: '#1565c0', country: '#b3261e', feature: '#2e7d32', region: '#6a1b9a', grid: '#37474f', physical: '#00838f' }

// 合并成一张总表，id 就是下标，地图 marker 用它来反查
const all = []
const byName = {}
function add(list, type) {
  list.forEach(item => {
    item.type = type
    item.typeLabel = TYPE_LABEL[type]
    item.color = TYPE_COLOR[type]
    item.id = all.length
    if (!item.zoom) item.zoom = 5.5
    item.facts = []
    // 国家和山河湖海是“点”，给出经纬度和按经度算的理论时区（国家取首都的位置）
    if (type === 'country' || type === 'feature') {
      item.coord = coordOf(item.lat, item.lng)
      item.zone = zoneName(Math.round(item.lng / 15))
    }
    item.points = KEY_POINTS[item.name] || []
    if (type === 'country') {
      const f = COUNTRY_FACTS[item.name] || []
      item.facts = [
        { k: '首都', v: item.capital },
        { k: '位置', v: f[0] || item.continent },
        { k: '面积', v: f[1] || '—' },
        { k: '人口', v: f[2] || '—' }
      ]
    }
    all.push(item)
    byName[item.name] = item
  })
}
add(continents, 'continent')
add(oceans, 'ocean')
add(countries, 'country')
add(features, 'feature')
add(regions, 'region')
add(grids, 'grid')
add(physical, 'physical')

module.exports = { continents, oceans, countries, features, regions, grids, physical, all, zoneName, byName, TYPE_LABEL, TYPE_COLOR }
