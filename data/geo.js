const TYPE_LABEL = { continent: '大洲', ocean: '大洋', country: '国家', feature: '地理事物' }
const TYPE_COLOR = { continent: '#b84300', ocean: '#1565c0', country: '#b3261e', feature: '#2e7d32' }

// 合并成一张总表，id 就是下标，地图 marker 用它来反查
const all = []
const byName = {}
function add(list, type) {
  list.forEach(item => {
    item.type = type
    item.typeLabel = TYPE_LABEL[type]
    item.color = TYPE_COLOR[type]
    item.id = all.length
    if (!item.zoom) item.zoom = 5.5
    item.facts = []
    if (type === 'country') {
      const f = COUNTRY_FACTS[item.name] || []
      item.facts = [
        { k: '首都', v: item.capital },
        { k: '位置', v: f[0] || item.continent },
        { k: '面积', v: f[1] || '—' },
        { k: '人口', v: f[2] || '—' }
      ]
    }
    all.push(item)
    byName[item.name] = item
  })
}
add(continents, 'continent')
add(oceans, 'ocean')
add(countries, 'country')
add(features, 'feature')

module.exports = { continents, oceans, countries, features, all, byName, TYPE_LABEL, TYPE_COLOR }
