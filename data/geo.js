// 经纬度和理论时区的文字
function coordOf(lat, lng) {
  return `${Math.abs(lat).toFixed(1)}°${lat >= 0 ? 'N' : 'S'} ${Math.abs(lng).toFixed(1)}°${lng >= 0 ? 'E' : 'W'}`
}
function zoneName(n) {
  if (n === 0) return '中时区'
  if (Math.abs(n) === 12) return '东西十二区'
  return n > 0 ? `东${n}区` : `西${-n}区`
}

